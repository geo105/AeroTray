function ax = crear_ejes(fig, pos_cm, E)
%CREAR_EJES Ejes en una posicion exacta [x y ancho alto] en cm dentro de la figura.
ax = axes('Parent', fig, 'Units', 'centimeters', 'Position', pos_cm, ...
    'FontName', E.fuente, 'FontSize', E.fs, 'LineWidth', E.lw_eje, ...
    'TickDir', 'out', 'Box', 'off', 'XGrid', 'on', 'YGrid', 'on', ...
    'Layer', 'top', 'NextPlot', 'add');
try, set(ax, 'GridColor', [0.15 0.15 0.15], 'GridAlpha', 0.12, 'TickLength', [0.015 0.015]); catch, end
end
